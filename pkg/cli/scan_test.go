// tarGz returns files as one gzip stream holding a tar archive.  A
// name ending in "/" is a directory.  The control section of an APK is
// written without the end-of-archive marker, so that it can be
// followed by the data section.
func tarGz(t *testing.T, files map[string]string, control bool) []byte {
	t.Helper()

	var buf bytes.Buffer
	gw := gzip.NewWriter(&buf)
	tw := tar.NewWriter(gw)
	for _, name := range []string{".PKGINFO", ".melange.yaml", "usr/", "usr/lib/", "usr/lib/pkgconfig/", "usr/lib/pkgconfig/foo.pc"} {
		data, ok := files[name]
		if !ok {
			continue
		}
		if dir, ok := strings.CutSuffix(name, "/"); ok {
			require.NoError(t, tw.WriteHeader(&tar.Header{
				Name:     dir,
				Mode:     0o755,
				Typeflag: tar.TypeDir,
			}))
			continue
		}
		require.NoError(t, tw.WriteHeader(&tar.Header{
			Name:     name,
			Mode:     0o644,
			Size:     int64(len(data)),
			Typeflag: tar.TypeReg,
		}))
		_, err := io.WriteString(tw, data)
		require.NoError(t, err)
	}
	if control {
		require.NoError(t, tw.Flush())
	} else {
		require.NoError(t, tw.Close())
	}
	require.NoError(t, gw.Close())

	return buf.Bytes()
}

// captureStdout returns what f writes to os.Stdout, which is where
// "melange scan" writes its diff.
func captureStdout(t *testing.T, f func()) string {
	t.Helper()

	r, w, err := os.Pipe()
	require.NoError(t, err)

	stdout := os.Stdout
	os.Stdout = w
	defer func() { os.Stdout = stdout }()

	out := make(chan string)
	go func() {
		b, _ := io.ReadAll(r)
		out <- string(b)
	}()

	f()
	require.NoError(t, w.Close())

	return <-out
}

// "melange scan" can only version a depend on what the build
// environment had installed, which it reads from the .melange.yaml
// recorded in the APK, and on what the repository's packages provide.
func TestScanVersionedDependsFromRecordedEnvironment(t *testing.T) {
	// melange writes "url = " with a trailing space when there is no URL.
	const pkginfo = `# Generated by melange
pkgname = foo-dev
pkgver = 1.0-r0
arch = x86_64
size = 42
origin = foo-dev
pkgdesc = foo development files
` + "url = \n" + `commit = 0123456789abcdef
maintainer = wolfi
builddate = 1700000000
depend = pc:bar
depend = pc:bar>=2.0-r1
provides = pc:foo=1.0-r0
datahash = 0000
`

	// The packages the build environment had installed, pinned as
	// melange records them.
	const recorded = `package:
  name: foo-dev
  version: "1.0"
  epoch: 0
environment:
  contents:
    packages:
      - bar-dev=2.0-r1
`

	const melangeYAML = `package:
  name: foo-dev
  version: "1.0"
  epoch: 0
  description: foo development files
environment:
  contents:
    packages:
      - bar-dev
pipeline:
  - runs: "true"
`

	const pc = "Name: foo\nDescription: foo\nVersion: 1.0\nRequires: bar\n"

	for _, tc := range []struct {
		name     string
		recorded bool
		wantDiff string
	}{{
		name:     "recorded environment",
		recorded: true,
	}, {
		// Without the pinned version of bar-dev, the depend on
		// pc:bar can't be versioned, so the scan disagrees with
		// the .PKGINFO on that line alone.
		name:     "no recorded environment",
		recorded: false,
		wantDiff: " depend = pc:bar\n-depend = pc:bar>=2.0-r1\n provides = pc:foo=1.0-r0\n",
	}} {
		t.Run(tc.name, func(t *testing.T) {
			ctx := slogtest.Context(t)

			repo := t.TempDir()
			archDir := filepath.Join(repo, "x86_64")
			require.NoError(t, os.MkdirAll(archDir, 0o755))

			control := map[string]string{".PKGINFO": pkginfo}
			if tc.recorded {
				control[".melange.yaml"] = recorded
			}
			data := map[string]string{
				"usr/":                     "",
				"usr/lib/":                 "",
				"usr/lib/pkgconfig/":       "",
				"usr/lib/pkgconfig/foo.pc": pc,
			}
			apkFile := append(tarGz(t, control, true), tarGz(t, data, false)...)
			require.NoError(t, os.WriteFile(filepath.Join(archDir, "foo-dev-1.0-r0.apk"), apkFile, 0o644))

			index, err := apk.ArchiveFromIndex(&apk.APKIndex{Packages: []*apk.Package{{
				Name:      "bar-dev",
				Version:   "2.0-r1",
				Arch:      "x86_64",
				Provides:  []string{"pc:bar=2.0-r1"},
				BuildTime: time.Unix(1600000000, 0),
			}}})
			require.NoError(t, err)
			b, err := io.ReadAll(index)
			require.NoError(t, err)
			require.NoError(t, os.WriteFile(filepath.Join(archDir, "APKINDEX.tar.gz"), b, 0o644))

			cfgFile := filepath.Join(t.TempDir(), "foo-dev.yaml")
			require.NoError(t, os.WriteFile(cfgFile, []byte(melangeYAML), 0o644))

			diff := captureStdout(t, func() {
				err = scanCmd(ctx, cfgFile, &scanConfig{
					repo:          repo,
					diff:          true,
					purlNamespace: "wolfi",
				})
			})
			if tc.wantDiff == "" {
				require.NoError(t, err)
				require.Empty(t, diff)
				return
			}
			require.ErrorContains(t, err, "saw diff")
			_, hunk, ok := strings.Cut(diff, "@@\n")
			require.True(t, ok, "no hunk in diff:\n%s", diff)
			require.Contains(t, hunk, tc.wantDiff)
			require.Equal(t, 1, strings.Count(hunk, "\n-")+strings.Count(hunk, "\n+"), "diff:\n%s", diff)
		})
	}
}
